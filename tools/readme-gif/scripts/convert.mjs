// Runs the REAL conversion on the demo photos with morph-cli (same engine as the app)
// and writes src/results.json with the sizes the progress view shows, formatted
// exactly like crates/morph-app (view.rs format_size, progress.rs size_change / summary_line).
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(ROOT, '..', '..');
const PHOTOS = path.join(ROOT, 'work', 'photos');
const OUT = path.join(ROOT, 'src', 'results.json');

const cli = [process.env.MORPH_CLI, path.join(REPO, 'target', 'release', 'morph-cli.exe'), path.join(REPO, 'target', 'debug', 'morph-cli.exe')]
  .find((p) => p && fs.existsSync(p));
if (!cli) {
  if (fs.existsSync(OUT)) { fs.writeFileSync(path.join(ROOT, 'src', 'results.js'), 'window.RESULTS = ' + fs.readFileSync(OUT, 'utf8') + ';\n'); console.warn('warn: morph-cli.exe not found (cargo build -p morph-cli --release); keeping the existing src/results.json'); process.exit(0); }
  console.error('error: morph-cli.exe not found and no src/results.json; run: cargo build -p morph-cli --release'); process.exit(1);
}

const inputs = fs.readdirSync(PHOTOS).filter((f) => /^IMG_\d+\.jpg$/.test(f)).sort();
for (const f of fs.readdirSync(PHOTOS)) if (/\.webp$/i.test(f)) fs.rmSync(path.join(PHOTOS, f)); // our own previous outputs
const r = spawnSync(cli, ['convert', '--action', 'image.convert', '--format', 'webp', '--quality', '80', ...inputs.map((f) => path.join(PHOTOS, f))], { encoding: 'utf8' });
if (r.status !== 0) { console.error(r.stdout, r.stderr); process.exit(1); }

const UNITS = ['B', 'KB', 'MB', 'GB', 'TB'];
const formatSize = (bytes) => {
  if (bytes < 1024) return `${bytes} ${UNITS[0]}`;
  let v = bytes, u = 0;
  while (v >= 1024 && u + 1 < UNITS.length) { v /= 1024; u++; }
  return `${v.toFixed(1)} ${UNITS[u]}`;
};
const change = (a, b) => { const p = Math.round((b - a) / a * 100); return p < 0 ? `−${-p}%` : `+${p}%`; };

let sumIn = 0, sumOut = 0;
const rows = inputs.map((f) => {
  const a = fs.statSync(path.join(PHOTOS, f)).size;
  const out = f.replace(/\.jpg$/, '.webp');
  const b = fs.statSync(path.join(PHOTOS, out)).size;
  sumIn += a; sumOut += b;
  return { name: f, output: out, bytesIn: a, bytesOut: b, sizeIn: formatSize(a), sizes: `${formatSize(a)} → ${formatSize(b)}`, change: change(a, b) };
});
const res = {
  generatedBy: `morph-cli convert --action image.convert --format webp --quality 80 (${path.relative(REPO, cli)})`,
  rows,
  totalIn: formatSize(sumIn),
  saved: formatSize(sumIn - sumOut),
  summary: `${rows.length} converted · saved ${formatSize(sumIn - sumOut)}`,
};
fs.writeFileSync(OUT, JSON.stringify(res, null, 2) + '\n');
console.log(res.summary, '| input', res.totalIn);
for (const x of rows) console.log(' ', x.name, x.sizes, x.change);
fs.writeFileSync(path.join(ROOT, 'src', 'results.js'), '// generated by scripts/convert.mjs from a real morph-cli run\nwindow.RESULTS = ' + JSON.stringify(res, null, 1) + ';\n');
